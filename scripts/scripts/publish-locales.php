function exportPhp(array $data, int $indent = 0): string
{
    $pad = str_repeat('    ', $indent);
    $inner = str_repeat('    ', $indent + 1);
    $lines = ['['];
    foreach ($data as $key => $value) {
        $renderedKey = is_int($key) ? (string) $key : var_export((string) $key, true);
        if (is_array($value)) {
            $lines[] = $inner.$renderedKey.' => '.exportPhp($value, $indent + 1).',';
        } else {
            $lines[] = $inner.$renderedKey.' => '.var_export($value, true).',';
        }
    }
    $lines[] = $pad.']';

    return implode("\n", $lines);
}

foreach ($locales as $code => $pack) {
    $dir = $root.'/lang/'.$code;
    if (! is_dir($dir) && ! mkdir($dir, 0777, true) && ! is_dir($dir)) {
        fwrite(STDERR, "Could not create {$dir}\n");
        exit(1);
    }

    $validation = $englishValidation;
    $validation['required'] = $pack['required'];
    $validation['in'] = $pack['in'];
    $validation['exists'] = $pack['in'];
    $validation['not_in'] = $pack['in'];
    $validation['enum'] = $pack['in'];
    $validation['attributes'] = array_replace($validation['attributes'], $pack['attributes']);
    file_put_contents($dir.'/validation.php', "<?php\n\nreturn ".exportPhp($validation).";\n");

    $ui = [];
    foreach ($pack['ui'] as $source => $translated) {
        $ui['m'.hash('fnv1a32', $source)] = $translated;
    }
    ksort($ui);
    file_put_contents($dir.'/ui.php', "<?php\n\nreturn ".exportPhp($ui).";\n");
    echo "published {$code}\n";
}
